%% Calls of the asn1rt_nif functions, through the stand-in asn1rt_nif, (asn1_erl_nif.c:1202-1318) and of the
%% generated BER codec AsnProbe, which calls asn1rt_nif:decode_ber_tlv/1.
%% check/0 compares the results with the results of the pinned ERTS
%% (OTP 29.1.1), which expected/0 holds.

%% The results of check/0 and nested/1 as binaries, after the load of
%% the NIF library from the path Lib. A second load in the same run gives
%% an error and keeps the library.
check_text(Lib) ->
    _ = asn1rt_nif:load(Lib),
    case check() of
        ok -> <<"ok">>;
        Mismatch -> term_to_binary(Mismatch)
    end.

%% encode_per_complete/1 of Data after the load of the NIF library.
per_complete(Lib, Data) ->
    _ = asn1rt_nif:load(Lib),
    asn1rt_nif:encode_per_complete(Data).

nested_text(Lib, N) ->
    _ = asn1rt_nif:load(Lib),
    case nested(N) of
        {{16, [_]}, <<>>} -> <<"decoded">>;
        {exit, {error, {asn1, {Reason, Position}}}} ->
            <<(atom_to_binary(Reason, utf8))/binary, " ", (integer_to_binary(Position))/binary>>
    end.

run(Fun) ->
    try Fun() catch Class:Reason -> {Class, Reason} end.

