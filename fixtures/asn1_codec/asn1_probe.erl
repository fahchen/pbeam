cases() ->
    Per = [run(fun() -> asn1rt_nif:encode_per_complete(I) end) || I <- per_inputs()],
    Ber = [run(fun() -> asn1rt_nif:decode_ber_tlv(I) end) || I <- ber_inputs()],
    Tlv = [run(fun() -> asn1rt_nif:encode_ber_tlv(I) end) || I <- tlv_inputs()],
    Codec = [run(fun() ->
                     {ok, Bytes} = 'AsnProbe':encode('Record', R),
                     {Bytes, 'AsnProbe':decode('Record', Bytes)}
                 end) || R <- codec_records()],
    Bad = [case run(fun() -> 'AsnProbe':decode('Record', B) end) of
               {error, {asn1, {Reason, _Stack}}} -> {error, Reason};
               Other -> Other
           end || B <- [<<16#30, 3, 16#80, 1>>, <<16#30, 16#80>>, <<1, 2, 3>>]],
    Per ++ Ber ++ Tlv ++ Codec ++ Bad.

check() ->
    compare(1, cases(), expected()).

compare(_, [], []) -> ok;
compare(N, [Same | Got], [Same | Want]) -> compare(N + 1, Got, Want);
compare(N, [Got | _], [Want | _]) -> {mismatch, N, Got, Want};
compare(N, Got, Want) -> {length, N, Got, Want}.

%% The decode result of N nested indefinite constructed values around
%% <<5,0>>.
nested(N) ->
    run(fun() -> asn1rt_nif:decode_ber_tlv(nest(N)) end).

nest(0) -> <<5, 0>>;
nest(N) -> <<16#30, 16#80, (nest(N - 1))/binary, 0, 0>>.

