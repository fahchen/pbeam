//! The BIF table: each BIF that the BIF dispatch knows, one line per entry.
//!
//! The table holds each non-`erlang` entry of the ERTS 29.1.1
//! `bif.tab` and each `erlang` BIF that PBeam implements, sorted by module,
//! name, and arity. On the pinned ERTS, `erlang:is_builtin/3` returns `true`
//! for each entry. ERTS binds each import of a BIF to the BIF and replaces
//! the body of each exported BIF stub with a call to the BIF (`emu_load.c`),
//! so a stub body such as `erlang:nif_error(undef)` never runs for an
//! external call. An entry gives one argument pattern with its body, or
//! `unsupported` when PBeam does not implement it. A call that no pattern
//! matches gives an unresolved MFA error.

